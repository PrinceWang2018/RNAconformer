"""WP2 baseline: run the legacy M1-M2.4 guide pipeline + M3 template export on benchmark targets.

The legacy exporter needs single-nucleotide templates that were never shipped; here it gets ideal
templates generated by the v2 builder (best case for the legacy path). Oracle 2D is used because
the legacy engine cannot predict 2D. Reports how many all-atom PDBs pass the legacy validation and
the v2 independent validator.

Usage: PYTHONPATH=src python benchmark/legacy_baseline.py --out benchmark/runs/legacy_baseline
"""
import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / 'src'))

from rnafold3d.build import load_geometry, ResidueBuilder, build_strand   # noqa: E402
from rnafold3d.structure_io import write_pdb, read_pdb                     # noqa: E402
from rnafold3d.checks import validate_model                                 # noqa: E402
from rnafold3d.build import atom_order                                     # noqa: E402
from rnafold3d.predict import read_dbn                                     # noqa: E402
from rnafold3d.metrics import compare                                      # noqa: E402


def make_templates(outdir):
    rb = ResidueBuilder(load_geometry())
    paths = {}
    for b in 'ACGU':
        res = build_strand(rb, ['A', b])[1]          # second residue has P/OP1/OP2/O5'
        p = outdir / f'{b}.pdb'
        write_pdb(p, [res], b)
        paths[b] = p
    return paths


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=str(ROOT / 'runs' / 'legacy_baseline'))
    ap.add_argument('--assemble', type=int, default=8)
    ap.add_argument('--steps', type=int, default=50)
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tpl = make_templates(out)
    ds = json.loads((ROOT / 'data' / 'dataset_v1.json').read_text())
    rows = []
    env = {'PYTHONPATH': str(ROOT.parent / 'src')}
    import os
    env = {**os.environ, **env}
    for s in sorted(ds['samples'], key=lambda s: s['length']):
        sid = s['sample_id']
        sdir = ROOT / 'data' / 'samples' / sid
        seq = (sdir / 'sequence.fasta').read_text().split('\n')[1].strip()
        dbn = read_dbn(sdir / 'oracle_2d.dbn', len(seq))
        tdir = out / sid
        tdir.mkdir(exist_ok=True)
        t0 = time.time()
        row = {'sample_id': sid, 'length': len(seq)}
        r1 = subprocess.run([sys.executable, '-m', 'rnafold3d', '--sequence', seq, '--structure', dbn,
                             '--assemble', str(a.assemble), '--pool-sampling', 'anneal', '--sample-steps', str(a.steps),
                             '--seed', '42', '--strict', '--output', str(tdir / 'm2.json')],
                            capture_output=True, text=True, env=env, timeout=3600)
        row['m1_m2_exit'] = r1.returncode
        if r1.returncode != 0:
            row['m1_m2_error'] = (r1.stderr.strip().splitlines() or [''])[-1][:200]
        else:
            obj = json.loads((tdir / 'm2.json').read_text())
            pool = obj.get('m2_4_pool', {})
            row['guide_candidates'] = pool.get('input_count')
            row['guide_selected'] = pool.get('selected_count')
            complete = [x for x in obj.get('assemblies', []) if x.get('full_chain_guides', {}).get('complete')]
            row['complete_guide_chains'] = len(complete)
            r2 = subprocess.run([sys.executable, '-m', 'rnafold3d.m3_cli', '--input', str(tdir / 'm2.json'),
                                 '--template-a', str(tpl['A']), '--template-c', str(tpl['C']), '--template-g', str(tpl['G']),
                                 '--template-u', str(tpl['U']), '--outdir', str(tdir / 'm3')],
                                capture_output=True, text=True, env=env, timeout=3600)
            row['m3_exit'] = r2.returncode
            if r2.returncode != 0:
                row['m3_error'] = (r2.stderr.strip().splitlines() or [''])[-1][:200]
            else:
                man = json.loads((tdir / 'm3' / 'manifest.json').read_text())
                confs = man['conformers']
                row['m3_candidates'] = len(confs)
                row['m3_exported'] = sum(1 for c in confs if c.get('file'))
                errs = {}
                for c in confs:
                    key = c.get('error', '').split(' ')[0] if c.get('error') else (
                        'failed_checks' if not c.get('file') else 'exported')
                    errs[key] = errs.get(key, 0) + 1
                row['m3_outcomes'] = errs
                link = [max(c['validation']['link_distances']) for c in confs if c.get('validation')]
                row['max_O3P_link_A'] = round(max(link), 2) if link else None
                v2pass = 0
                for c in confs:
                    if c.get('file'):
                        ch, _ = read_pdb(tdir / 'm3' / c['file'])
                        chain = next(iter(ch.values()))
                        res = [{k: v for k, v in r.atoms.items() if k in atom_order(r.base)} for r in chain.residues]
                        v2pass += validate_model(seq, res)['passed']
                row['v2_validator_pass'] = v2pass
        row['time_s'] = round(time.time() - t0, 1)
        rows.append(row)
        print(json.dumps(row), flush=True)
    (out / 'legacy_baseline.json').write_text(json.dumps(rows, indent=1))


if __name__ == '__main__':
    main()
